import 'dart:ui';
import 'package:flutter/material.dart';
import 'package:cached_network_image/cached_network_image.dart';
import '../l10n/app_localizations.dart';
import '../models/history_master_model.dart';
import '../utils/timeline_calculator.dart';

/// HOME タブビュー（AI生成表記＆画像ボトムシート対応）
class HomeView extends StatelessWidget {
  final AppDateResult? appDate;
  final HistoryMasterModel? historyMaster;

  const HomeView({
    super.key,
    required this.appDate,
    required this.historyMaster,
  });

  void _showDescriptionBottomSheet(BuildContext context) {
    final l10n = AppLocalizations.of(context)!;
    final isDarkMode = Theme.of(context).brightness == Brightness.dark;
    final langCode = Localizations.localeOf(context).languageCode;

    final descText = historyMaster != null
        ? historyMaster!.getDescription(langCode)
        : l10n.homeDefaultDescription;

    final titleText = historyMaster != null
        ? historyMaster!.getTitle(langCode)
        : (appDate != null ? appDate!.toLocalizedFormattedString(context) : '');

    final imagePath = historyMaster?.backgroundImagePath ?? '';

    final sheetBgColor = isDarkMode
        ? Colors.black.withOpacity(0.65)
        : Colors.white.withOpacity(0.75);
    final borderColor = isDarkMode
        ? Colors.white.withOpacity(0.15)
        : Colors.white.withOpacity(0.50);
    final handleColor = isDarkMode
        ? Colors.white.withOpacity(0.30)
        : Colors.black.withOpacity(0.20);
    final textColor = isDarkMode ? Colors.white : Colors.black87;
    final subTextColor = isDarkMode ? Colors.white70 : Colors.black54;

    showModalBottomSheet(
      context: context,
      backgroundColor: Colors.transparent,
      isScrollControlled: true,
      builder: (BuildContext context) {
        return ClipRRect(
          borderRadius: const BorderRadius.vertical(top: Radius.circular(24)),
          child: BackdropFilter(
            filter: ImageFilter.blur(sigmaX: 15, sigmaY: 15),
            child: Container(
              padding: const EdgeInsets.fromLTRB(20, 12, 20, 32),
              decoration: BoxDecoration(
                color: sheetBgColor,
                borderRadius:
                    const BorderRadius.vertical(top: Radius.circular(24)),
                border: Border.all(color: borderColor),
              ),
              child: Column(
                mainAxisSize: MainAxisSize.min,
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Center(
                    child: Container(
                      width: 40,
                      height: 4,
                      decoration: BoxDecoration(
                        color: handleColor,
                        borderRadius: BorderRadius.circular(2),
                      ),
                    ),
                  ),
                  const SizedBox(height: 16),

                  // 🖼 歴史背景画像
                  ClipRRect(
                    borderRadius: BorderRadius.circular(16),
                    child: AspectRatio(
                      aspectRatio: 16 / 9,
                      child: imagePath.isNotEmpty
                          ? CachedNetworkImage(
                              imageUrl: imagePath,
                              fit: BoxFit.cover,
                              placeholder: (_, __) => Container(
                                color: Colors.grey.withOpacity(0.3),
                                child: const Center(
                                    child: CircularProgressIndicator()),
                              ),
                              errorWidget: (_, __, ___) => Container(
                                color: Colors.grey.withOpacity(0.3),
                                child: Icon(Icons.auto_stories,
                                    size: 48, color: textColor),
                              ),
                            )
                          : Container(
                              color: Colors.grey.withOpacity(0.3),
                              child: Icon(Icons.auto_stories,
                                  size: 48, color: textColor),
                            ),
                    ),
                  ),
                  const SizedBox(height: 6),

                  // 🤖 EU AI Act 対応透明性表記
                  Align(
                    alignment: Alignment.centerRight,
                    child: Text(
                      langCode == 'en'
                          ? '* Image generated by AI'
                          : '※ この画像は生成AIにより作成されています',
                      style: TextStyle(
                        fontSize: 10,
                        color: subTextColor.withOpacity(0.7),
                        fontStyle: FontStyle.italic,
                      ),
                    ),
                  ),
                  const SizedBox(height: 14),

                  if (titleText.isNotEmpty) ...[
                    Text(
                      titleText,
                      style: TextStyle(
                        fontSize: 18,
                        fontWeight: FontWeight.bold,
                        color: textColor,
                      ),
                    ),
                    const SizedBox(height: 12),
                  ],

                  Text(
                    descText,
                    style: TextStyle(
                      fontSize: 14,
                      height: 1.6,
                      color: subTextColor,
                      fontWeight: FontWeight.w400,
                    ),
                  ),
                ],
              ),
            ),
          ),
        );
      },
    );
  }

  @override
  Widget build(BuildContext context) {
    final isDarkMode = Theme.of(context).brightness == Brightness.dark;

    final dateLabel = appDate != null
        ? appDate!.toLocalizedFormattedString(context)
        : '720 BCE 06/28';

    final buttonBgColor = isDarkMode
        ? Colors.black.withOpacity(0.40)
        : Colors.white.withOpacity(0.40);
    final borderColor = isDarkMode
        ? Colors.white.withOpacity(0.20)
        : Colors.white.withOpacity(0.50);
    final contentColor = isDarkMode ? Colors.white : Colors.black87;

    return Align(
      alignment: Alignment.topCenter,
      child: Padding(
        padding: const EdgeInsets.symmetric(horizontal: 24.0),
        child: InkWell(
          onTap: () => _showDescriptionBottomSheet(context),
          borderRadius: BorderRadius.circular(20),
          child: ClipRRect(
            borderRadius: BorderRadius.circular(20),
            child: BackdropFilter(
              filter: ImageFilter.blur(sigmaX: 10, sigmaY: 10),
              child: Container(
                padding:
                    const EdgeInsets.symmetric(horizontal: 24, vertical: 12),
                decoration: BoxDecoration(
                  color: buttonBgColor,
                  borderRadius: BorderRadius.circular(20),
                  border: Border.all(color: borderColor),
                ),
                child: Row(
                  mainAxisSize: MainAxisSize.min,
                  children: [
                    Icon(
                      Icons.directions_run,
                      color: isDarkMode
                          ? Colors.purpleAccent[100]
                          : Colors.deepPurple,
                      size: 20,
                    ),
                    const SizedBox(width: 8),
                    Text(
                      dateLabel,
                      style: TextStyle(
                        fontSize: 15,
                        fontWeight: FontWeight.bold,
                        color: contentColor,
                      ),
                    ),
                  ],
                ),
              ),
            ),
          ),
        ),
      ),
    );
  }
}